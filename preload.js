const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  setTheme: t => ipcRenderer.send('theme:set', t),
  renameChat: (id, t) => ipcRenderer.invoke('chats:rename', id, t),
  pinChat: (id, p) => ipcRenderer.invoke('chats:pin', id, p),
  pickFolder: () => ipcRenderer.invoke('ws:pick'),
  providers: () => ipcRenderer.invoke('providers:list'),
  setKey: (p, n, k) => ipcRenderer.invoke('key:set', p, n, k),
  useKey: (p, n) => ipcRenderer.invoke('key:use', p, n),
  delKey: (p, n) => ipcRenderer.invoke('key:del', p, n),
  models: (p, u) => ipcRenderer.invoke('models:list', p, u),
  agents: () => ipcRenderer.invoke('agents:list'),
  getAgent: id => ipcRenderer.invoke('agents:get', id),
  saveAgent: (id, t) => ipcRenderer.invoke('agents:save', id, t),
  openAgents: () => ipcRenderer.invoke('agents:open'),
  getPrices: () => ipcRenderer.invoke('prices:get'),
  setPrices: o => ipcRenderer.invoke('prices:set', o),
  files: q => ipcRenderer.invoke('ws:files', q),
  skills: () => ipcRenderer.invoke('skills:list'),
  saveSkills: l => ipcRenderer.invoke('skills:save', l),
  tree: rel => ipcRenderer.invoke('ws:tree', rel),
  chats: tab => ipcRenderer.invoke('chats:list', tab),
  openChat: id => ipcRenderer.invoke('chats:open', id),
  delChat: id => ipcRenderer.invoke('chats:delete', id),
  reset: tab => ipcRenderer.invoke('chat:reset', tab),
  send: (t, s) => ipcRenderer.invoke('agent:send', t, s),
  approve: (id, ok, scope) => ipcRenderer.send('agent:approve', id, ok, scope),
  undo: () => ipcRenderer.invoke('changes:undo'),
  getPerms: () => ipcRenderer.invoke('perms:get'),
  setPerms: t => ipcRenderer.invoke('perms:set', t),
  stop: () => ipcRenderer.send('agent:stop'),
  onEvent: cb => ipcRenderer.on('agent:event', (_e, ev) => cb(ev))
});
